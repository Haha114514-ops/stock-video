def main(ep_dir):
    os.makedirs(ep_dir, exist_ok=True)
    out = os.path.join(ep_dir, "要素核对单.md")
    lines = ["# 要素核对单 · %s · 生成于 %s" % (os.path.basename(os.path.dirname(ep_dir) or ep_dir), date.today().isoformat()),
             "",
             "> 开工前置门（修1）：写文案前逐条确认；全部 [x] 后才允许动工。判据列=验收口径。",
             ""]
    cur = None
    for cat, item, crit in ITEMS:
        if cat != cur:
            lines += ["## " + cat, ""]
            cur = cat
        lines.append("- [ ] %s ｜ 判据：%s" % (item, crit))
    lines += ["", "---", "确认人：＿＿＿＿  日期：＿＿＿＿"]
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print("核对单已生成:", out, "（%d 项）" % len(ITEMS))
    print("写文案前逐条 [x]；全绿才开工。")


